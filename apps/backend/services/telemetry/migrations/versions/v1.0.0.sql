CREATE INDEX IF NOT EXISTS ix_events_warning_app_level_ts ON events_warning (app, level, ts_server);
CREATE INDEX IF NOT EXISTS ix_events_warning_ts ON events_warning (ts_server);

-- ─── events_business ────────────────────────────────────────────
-- Arbitrary client-side business events (named, with payload).
CREATE TABLE IF NOT EXISTS events_business (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  ts_server timestamp(3) NOT NULL,
  ts_client timestamp(3) DEFAULT NULL,
  app varchar(32) NOT NULL,
  env varchar(32) NOT NULL,
  release varchar(128) NOT NULL DEFAULT '',
  user_id varchar(64) DEFAULT NULL,
  username varchar(120) DEFAULT NULL,
  is_admin smallint NOT NULL DEFAULT 0,
  device_id varchar(128) NOT NULL,
  session_id varchar(128) NOT NULL,
  trace_id varchar(64) DEFAULT NULL,
  route varchar(256) NOT NULL DEFAULT '',
  user_agent varchar(512) NOT NULL DEFAULT '',
  name varchar(128) NOT NULL,
  payload jsonb DEFAULT NULL,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_events_business_app_name_ts ON events_business (app, name, ts_server);
CREATE INDEX IF NOT EXISTS ix_events_business_ts ON events_business (ts_server);

-- ─── sessions ───────────────────────────────────────────────────
-- Composite PK lets ingestion use INSERT ... ON CONFLICT DO UPDATE so
-- multiple batches in the same session merge into one row (replaces the
-- ClickHouse ReplacingMergeTree(ts_server) semantics).
CREATE TABLE IF NOT EXISTS sessions (
  app varchar(32) NOT NULL,
  session_id varchar(128) NOT NULL,
  ts_server timestamp(3) NOT NULL,
  env varchar(32) NOT NULL,
  release varchar(128) NOT NULL DEFAULT '',
  user_id varchar(64) DEFAULT NULL,
  username varchar(120) DEFAULT NULL,
  is_admin smallint NOT NULL DEFAULT 0,
  device_id varchar(128) NOT NULL,
  route varchar(256) NOT NULL DEFAULT '',
  user_agent varchar(512) NOT NULL DEFAULT '',
  event_count integer NOT NULL DEFAULT 0,
  PRIMARY KEY (app, session_id)
);
CREATE INDEX IF NOT EXISTS ix_sessions_ts ON sessions (ts_server);

UPDATE migration SET version = 'v1.0.0', update_time = NOW() WHERE id = 1;

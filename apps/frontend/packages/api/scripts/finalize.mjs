import { access, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const services = ["admin", "canvas", "chat", "iam", "knowledge", "storage", "telemetry"];

for (const service of services) {
  const path = resolve(packageRoot, "src", `${service}-server.ts`);
  await access(path);
}

const runtimeFiles = [
  "auth-fetch.ts",
  "canvas-stream.test.ts",
  "canvas-stream.ts",
  "chat-stream.ts",
  "http.ts",
  "orval-mutator.ts",
  "session.ts",
  "storage-runtime.test.ts",
  "storage-runtime.ts",
  "storage.ts",
];
const allowedFiles = new Set([...services.map((service) => `${service}-server.ts`), ...runtimeFiles]);
const unexpectedFiles = (await readdir(resolve(packageRoot, "src"))).filter((file) => !allowedFiles.has(file));
if (unexpectedFiles.length > 0) {
  throw new Error(`unexpected handwritten API modules: ${unexpectedFiles.join(", ")}`);
}

const index = `/**
 * Generated by pnpm codegen. Do not edit manually.
 */
${services.map((service) => `export * as ${service} from "./src/${service}-server";`).join("\n")}
export * from "./src/auth-fetch";
export * from "./src/canvas-stream";
export * from "./src/chat-stream";
export * from "./src/http";
export * from "./src/session";
export * from "./src/storage-runtime";
`;
await writeFile(resolve(packageRoot, "index.ts"), index);
